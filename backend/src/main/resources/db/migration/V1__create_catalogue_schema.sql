-- Catalogue: cities, categories, activities and their EN/FR translations.
-- Translatable text lives in *_translation tables keyed by locale, so a new
-- language means new rows, not new columns.

CREATE TABLE city (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           VARCHAR(80)  NOT NULL,
    hero_image_url VARCHAR(500),
    sort_order     INT          NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_city_slug UNIQUE (slug)
);

CREATE TABLE city_translation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id          BIGINT       NOT NULL REFERENCES city (id) ON DELETE CASCADE,
    locale           VARCHAR(5)   NOT NULL,
    name             VARCHAR(120) NOT NULL,
    description      TEXT,
    meta_title       VARCHAR(120),
    meta_description VARCHAR(320),
    CONSTRAINT uq_city_translation_locale UNIQUE (city_id, locale)
);

CREATE TABLE category (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(80) NOT NULL,
    icon       VARCHAR(60),
    sort_order INT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_category_slug UNIQUE (slug)
);

CREATE TABLE category_translation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT       NOT NULL REFERENCES category (id) ON DELETE CASCADE,
    locale      VARCHAR(5)   NOT NULL,
    name        VARCHAR(120) NOT NULL,
    CONSTRAINT uq_category_translation_locale UNIQUE (category_id, locale)
);

CREATE TABLE activity (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(160)  NOT NULL,
    city_id          BIGINT        NOT NULL REFERENCES city (id),
    category_id      BIGINT        NOT NULL REFERENCES category (id),
    type             VARCHAR(20)   NOT NULL,
    price_adult_eur  NUMERIC(10, 2) NOT NULL,
    price_child_eur  NUMERIC(10, 2) NOT NULL,
    duration_minutes INT           NOT NULL,
    max_group_size   INT           NOT NULL,
    operating_days   VARCHAR(80)   NOT NULL,
    meeting_point    VARCHAR(255),
    latitude         NUMERIC(9, 6),
    longitude        NUMERIC(9, 6),
    tripadvisor_url  VARCHAR(500),
    status           VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_activity_slug UNIQUE (slug),
    CONSTRAINT ck_activity_type CHECK (type IN ('EXCURSION', 'ACTIVITY')),
    CONSTRAINT ck_activity_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT ck_activity_price_adult CHECK (price_adult_eur >= 0),
    CONSTRAINT ck_activity_price_child CHECK (price_child_eur >= 0),
    CONSTRAINT ck_activity_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_activity_group_size CHECK (max_group_size > 0)
);

CREATE INDEX ix_activity_city_status ON activity (city_id, status);
CREATE INDEX ix_activity_category_status ON activity (category_id, status);

CREATE TABLE activity_translation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id      BIGINT       NOT NULL REFERENCES activity (id) ON DELETE CASCADE,
    locale           VARCHAR(5)   NOT NULL,
    title            VARCHAR(200) NOT NULL,
    summary          VARCHAR(500),
    description      TEXT,
    itinerary        TEXT,
    included         TEXT,
    not_included     TEXT,
    meta_title       VARCHAR(120),
    meta_description VARCHAR(320),
    CONSTRAINT uq_activity_translation_locale UNIQUE (activity_id, locale)
);

CREATE TABLE activity_image (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT       NOT NULL REFERENCES activity (id) ON DELETE CASCADE,
    url         VARCHAR(500) NOT NULL,
    alt_text    VARCHAR(255),
    sort_order  INT          NOT NULL DEFAULT 0
);

CREATE INDEX ix_activity_image_activity ON activity_image (activity_id, sort_order);
